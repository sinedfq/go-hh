const base = (process.argv[2] || 'http://127.0.0.1:3000').replace(/\/$/,'')
async function request(path,options={}) {
    const response=await fetch(`${base}${path}`,options)
    assert.ok(response.ok,`${options.method||'GET'} ${path}: ${response.status}`)
    return response
}
